export function stilBul(id) { return KATALOG.find(s => s.id === id) || null; }
export function sahneBul(stil, sahne) { const s = stilBul(stil); return s ? s.sahneler.find(x => x.id === sahne) || null : null; }
/** "Kelebek · Dolphin kick" / "Serbest · Nefes" */
export function etiket(o) {
  const s = stilBul(o.stil); const sc = sahneBul(o.stil, o.sahne);
  if (!s || !sc) return '?';
  if (o.konu) { const k = sc.konular.find(t => t[0] === o.konu); if (k) return s.ad + ' · ' + k[1]; }
  return s.ad + ' · ' + sc.ad;
}
